"""Vectors shared with the server (tests/unit/ntag424-diversify.test.ts).

The fixture pins our key derivation and SUN output so the Python encoder and the TypeScript
verifier can't drift apart. Regenerate (only when intentionally changing the scheme, which would
break every encoded tag) with:  NTAG424_REGENERATE_VECTORS=1 pytest tests/test_vectors_shared.py
"""

import json
import os
from pathlib import Path
from urllib.parse import parse_qs, urlsplit

from ntag424_encoder.commands import Ntag424
from ntag424_encoder.crypto import derive_per_tag_key, derive_system_key
from ntag424_encoder.personalize import personalize_tag
from ntag_sim import DeterministicRng, SimulatedNtag424
from test_personalize import tap

FIXTURE = Path(__file__).resolve().parents[2] / "tests" / "fixtures" / "ntag424-vectors.json"
MASTER = bytes.fromhex("000102030405060708090A0B0C0D0E0F")
UIDS = ["04A1B2C3D4E5F6", "04000000000000", "04FFFFFFFFFFFF"]


def build_vectors() -> dict:
    derivation = [
        {"uid": uid, "slot": slot, "key": derive_per_tag_key(MASTER, bytes.fromhex(uid), slot).hex().upper()}
        for uid in UIDS
        for slot in range(5)
    ]
    derivation.append({"uid": "", "slot": "system", "key": derive_system_key(MASTER, 2).hex().upper()})

    taps = []
    for uid in UIDS[:2]:
        sim = SimulatedNtag424(bytes.fromhex(uid), DeterministicRng(b"tag-" + uid.encode()))
        personalize_tag(Ntag424(sim, DeterministicRng(b"host-" + uid.encode())), MASTER, f"https://tags.example.com/t/tag_{uid}")
        for _ in range(2):
            q = parse_qs(urlsplit(tap(sim)).query)
            taps.append({"picc": q["picc"][0], "cmac": q["cmac"][0], "uid": uid, "counter": sim.read_ctr})

    return {
        "_comment": "Generated by encoder/tests/test_vectors_shared.py; verified by both implementations.",
        "masterKey": MASTER.hex().upper(),
        "derivation": derivation,
        "taps": taps,
    }


def test_shared_vectors_match_fixture():
    vectors = build_vectors()
    if os.environ.get("NTAG424_REGENERATE_VECTORS") == "1":
        FIXTURE.write_text(json.dumps(vectors, indent=2) + "\n")
    assert json.loads(FIXTURE.read_text()) == vectors
